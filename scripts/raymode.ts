/** Scene adapters must match raster part poses, preserve the coast and omit broken parts. */
import { Quaternion, Vector3 } from 'three';
import { TEST_PLANE } from '../src/craft/testPlane.ts';
import { debrisShape, flightShapes, hangarShapes } from '../src/render/raytrace/sceneShapes.ts';
import { intersectShape } from '../src/render/raytrace/shapes.ts';
import { initPhysics, Simulation } from '../src/sim/Simulation.ts';
await initPhysics();
const sim = new Simulation(TEST_PLANE);
let count = 0;
const check = (ok: boolean, name: string) => { if (!ok) throw new Error(name); console.log(`PASS ${name}`); count++; };
const position = new Vector3(1, 2, 3), rotation = new Quaternion().setFromAxisAngle(new Vector3(0,1,0),Math.PI/2);
const hangar = hangarShapes(sim, position, rotation);
const expected = new Vector3(...TEST_PLANE.parts[0].position).applyQuaternion(rotation).add(position);
check(hangar[0].position.distanceTo(expected)<1e-9,'hangar craft follows displayed root transform');
const debris = debrisShape({type:'cylinder',axis:'x',radius:1,length:4},position,rotation,'#00eaff');
check(new Vector3(0,1,0).applyQuaternion(debris.rotation).distanceTo(new Vector3(-1,0,0).applyQuaternion(rotation))<1e-9,'debris cylinder primitive axis composes with detached-body rotation');
const flight = flightShapes(sim,sim.position,sim.rotation,new Vector3(0,2,360));
const planes=flight.filter(s=>s.kind==='plane');
const downward=new Vector3(0,-1,0);
check(planes.some(p=>!!intersectShape(new Vector3(0,10,0),downward,p)),'runway region has traced land');
check(!intersectShape(new Vector3(3000,10,0),downward,planes[0]),'land grid stops at the coast');
check(!!intersectShape(new Vector3(3000,10,0),downward,planes[1]),'ocean traced east of the coast');
check(!intersectShape(new Vector3(0,10,0),downward,planes[1]),'ocean cannot cover inland runway');
const part=sim.craft.parts.find(p=>p.id.includes('wing'))??sim.craft.parts[0];
const initial=hangarShapes(sim,position,rotation).length;
sim.craft.detachPart(part.id);
check(hangarShapes(sim,position,rotation).length===initial-1,'detached parts omitted from intact craft');
check(flight.length<256,'default scene adapters stay within shape capacity');
sim.world.free();
console.log(`${count} ray-trace mode scene checks passed`);
